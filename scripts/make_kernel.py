def dump(obj):
    for attr in ('model_dump', 'dict'):
        if hasattr(obj, attr):
            try:
                return json.loads(json.dumps(getattr(obj, attr)(), default=str))
            except Exception:
                pass
    return {k: str(v) for k, v in vars(obj).items()}


(OUT / 'patches').mkdir(exist_ok=True)
