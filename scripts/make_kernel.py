#!/usr/bin/env python3
"""Generate a self-contained Kaggle kernel that evaluates our submission.

The built submission zip is embedded as base64, so no extra dataset upload is
needed. The kernel follows the official "Getting Started" notebook: install the
wheelhouse, start vLLM, run swegemma's Evaluator on the subprocess sandbox.

  python scripts/build.py --model e4b
  python scripts/make_kernel.py --user <kaggle-user> --tag smoke --task-ids rich_3676
  kaggle kernels push -p kaggle/smoke
  kaggle kernels status <kaggle-user>/gemma-agent-smoke
  kaggle kernels output <kaggle-user>/gemma-agent-smoke -p results/smoke
"""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

MODELS = {
    "e4b": "gemma-4-e4b-it-qat-w4a16-ct",
    "e2b": "gemma-4-e2b-it-qat-w4a16-ct",
    "12b": "gemma-4-12b-it-qat-w4a16-ct",
    "31b": "gemma-4-31b-it-qat-w4a16-ct",
}

TEMPLATE = r'''
# Auto-generated by scripts/make_kernel.py. Do not edit by hand.
import asyncio, base64, concurrent.futures, glob, importlib, io, json, logging, os, re
import shutil, subprocess, sys, time, traceback, zipfile
from pathlib import Path

TAG = __TAG__
MODEL_NAME = __MODEL__
TASK_IDS = __TASK_IDS__          # empty list = all tasks
SKIP_AGENT_PATCH = __SKIP__      # True = baseline verification only, no LLM
SUBMISSION_B64 = __ZIP__

for k, v in {
    'TRANSFORMERS_NO_TF': '1', 'TRANSFORMERS_NO_FLAX': '1', 'TRANSFORMERS_OFFLINE': '1',
    'VLLM_NO_USAGE_STATS': '1', 'VLLM_WORKER_MULTIPROC_METHOD': 'spawn',
    'VLLM_ENGINE_READY_TIMEOUT_S': '1200', 'VLLM_MEMORY_PROFILER_ESTIMATE_CUDAGRAPHS': '1',
    'NCCL_DEBUG': 'WARN', 'LITELLM_LOCAL_MODEL_COST_MAP': 'True', 'LITELLM_TELEMETRY': 'False',
    'LITELLM_LOG': 'WARNING', 'PYTORCH_CUDA_ALLOC_CONF': 'expandable_segments:True',
    'OTEL_SDK_DISABLED': 'true', 'OTEL_PYTHON_DISABLED': 'true',
}.items():
    os.environ[k] = v
os.environ.setdefault('OPENAI_API_KEY', 'EMPTY')
os.environ.setdefault('LOCAL_API_KEY', 'EMPTY')


def quiet():
    for name in ('LiteLLM', 'LiteLLM Router', 'LiteLLM Proxy', 'litellm', 'httpx', 'httpcore',
                 'openai', 'urllib3', 'opentelemetry', 'opentelemetry.context'):
        lg = logging.getLogger(name)
        lg.setLevel(logging.WARNING)
        if 'litellm' in name.lower():
            lg.propagate = False
            lg.handlers.clear()


def first_existing(*patterns):
    for p in patterns:
        hits = sorted(glob.glob(p))
        if hits:
            return Path(hits[0])
    raise FileNotFoundError(f'none of {patterns} exist; check kernel inputs')


quiet()
WHEELHOUSE = first_existing('/kaggle/input/datasets/metric/gemma-4-developer-agent-wheelhouse',
                            '/kaggle/input/gemma-4-developer-agent-wheelhouse')
DATA_DIR = first_existing('/kaggle/input/competitions/gemma-4-developer-agent',
                          '/kaggle/input/gemma-4-developer-agent')
WORK = Path('/kaggle/working')
OUT = WORK / 'results' / TAG
OUT.mkdir(parents=True, exist_ok=True)
print(f'wheelhouse={WHEELHOUSE}\ndata={DATA_DIR}', flush=True)

# 1. Install harness wheels (same fix-ups as the official starter notebook).
for pth in glob.glob('/usr/local/lib/python*/*-packages/*cutlass*.pth'):
    try:
        os.unlink(pth)
    except OSError:
        pass
tmp_whl = Path('/tmp/wheelhouse')
tmp_whl.mkdir(parents=True, exist_ok=True)
for w in WHEELHOUSE.glob('*.whl'):
    if 'cutlass' in w.name.lower():
        continue
    name = w.name.replace('cu128', '+cu128') if ('cu128' in w.name and '+' not in w.name) else w.name
    t = tmp_whl / name
    if not t.exists():
        try:
            os.symlink(w, t)
        except OSError:
            shutil.copyfile(w, t)
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', '--no-deps', '--force-reinstall',
                *sorted(str(w) for w in tmp_whl.glob('*.whl'))], check=True)
importlib.invalidate_caches()
quiet()

# 2. Unpack our submission.
AGENT_DIR = WORK / 'submission'
shutil.rmtree(AGENT_DIR, ignore_errors=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(SUBMISSION_B64))).extractall(AGENT_DIR)
print('submission files:', sorted(str(p.relative_to(AGENT_DIR)) for p in AGENT_DIR.rglob('*') if p.is_file()))

from adk_submission import validate_directory
from swegemma.config import EvalConfig, build_submission_limits
from swegemma.models import load_tasks

limits, gen_constraints = build_submission_limits()
validate_directory(AGENT_DIR, limits=limits)
print('validate_directory: OK', flush=True)

TASKS_PATH = DATA_DIR / 'tasks.jsonl'
tasks = load_tasks(TASKS_PATH)
if TASK_IDS:
    keep = set(TASK_IDS)
    tasks = [t for t in tasks if t.instance_id in keep]
print(f'{len(tasks)} task(s): {[t.instance_id for t in tasks][:10]}', flush=True)

# 3. Start vLLM unless this is a baseline-only run.
server = None
models = None
adapters = None
if not SKIP_AGENT_PATCH:
    import litellm
    import torch
    from adk_submission import VllmConfig, VllmServer, discover_adapters
    from adk_submission.discovery import discover_declared_models
    from swegemma.config import ALLOWED_ADAPTER_EXTENSIONS
    litellm.drop_params = True
    declared = discover_declared_models(AGENT_DIR)
    assert declared == {MODEL_NAME}, f'declared models {declared} != {MODEL_NAME}'
    model_path = first_existing(f'/kaggle/input/models/google/gemma-4/other/{MODEL_NAME}/*',
                                f'/kaggle/input/gemma-4/other/{MODEL_NAME}/*')
    adapters = discover_adapters(str(AGENT_DIR), adapter_extensions=ALLOWED_ADAPTER_EXTENSIONS)
    amap = getattr(adapters, 'adapters', None) or {}
    ranks = [r for i in amap.values() if (r := getattr(i, 'rank', None))]
    gpus = torch.cuda.device_count() if torch.cuda.is_available() else 1
    tp = 4 if gpus >= 4 else (2 if gpus >= 2 else 1)
    extra = (('--hf-overrides', '{"architectures": ["Gemma4ForCausalLM"], "model_type": "gemma4"}')
             if MODEL_NAME == 'gemma-4-12b-it-qat-w4a16-ct' else ())
    cfg = VllmConfig(model=str(model_path), port=8000, host='127.0.0.1', tool_call_parser='gemma4',
                     reasoning_parser='gemma4', max_model_len=32768,
                     dtype='bfloat16' if torch.cuda.is_bf16_supported() else 'auto',
                     gpu_memory_utilization=0.90, enable_auto_tool_choice=True,
                     enable_lora=bool(amap), max_loras=max(1, len(amap)),
                     max_lora_rank=max(ranks) if ranks else 128, scheduler_reserve_full_isl=False,
                     tensor_parallel_size=tp, startup_timeout=60 * 20, extra_args=extra)
    t0 = time.time()
    server = VllmServer(cfg, adapter_manifest=adapters)
    server.start()
    print(f'vLLM up on {server.base_url} tp={tp} gpus={gpus} in {time.time() - t0:.0f}s', flush=True)
    models = server.create_model_registry(aliases=[MODEL_NAME], model_prefix='openai/',
                                          api_key=os.environ['LOCAL_API_KEY'])

# 4. Evaluate.
import yaml
from google.adk.agents.context_cache_config import ContextCacheConfig
from google.adk.apps._configs import EventsCompactionConfig
from swegemma.evaluate import Evaluator


def run_sync(fn, *a, **kw):
    call = lambda: fn(*a, **kw)
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None
    if loop is not None and loop.is_running():
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
            return pool.submit(lambda: asyncio.run(call())).result()
    res = call()
    return asyncio.run(res) if asyncio.iscoroutine(res) else res


ev = (yaml.safe_load((AGENT_DIR / 'eval_config.yaml').read_text()) or {}).get('evaluation', {})
cfg_kwargs = dict(
    tasks_path=TASKS_PATH, snapshots_dir=DATA_DIR / 'snapshots', results_dir=OUT,
    submission_dir=AGENT_DIR, models=models, sandbox='subprocess',
    timeout_seconds=int(ev.get('timeout_seconds', 300)), verification_timeout_seconds=300,
    max_time_minutes=float(ev.get('max_time_minutes', 60.0)),
    max_tool_calls=int(ev.get('max_tool_calls', 100)),
    max_turns=int(ev['max_turns']) if ev.get('max_turns') is not None else None,
    limits=limits, generation_constraints=gen_constraints, adapter_manifest=adapters,
    context_cache_config=ContextCacheConfig(min_tokens=2048, ttl_seconds=1800, cache_intervals=10),
    events_compaction_config=EventsCompactionConfig(compaction_interval=15, overlap_size=2,
                                                    token_threshold=14336, event_retention_size=5),
    graph_dir=str(DATA_DIR / 'graphs'), embeddings_dir=str(DATA_DIR / 'embeddings'),
    wheels_dir=DATA_DIR / 'wheels', verbose=False,
)
if SKIP_AGENT_PATCH:
    cfg_kwargs['skip_agent_patch'] = True
evaluator = Evaluator(EvalConfig(**cfg_kwargs))


def dump(obj):
    for attr in ('model_dump', 'dict'):
        if hasattr(obj, attr):
            try:
                return json.loads(json.dumps(getattr(obj, attr)(), default=str))
            except Exception:
                pass
    return {k: str(v) for k, v in vars(obj).items()}


(OUT / 'patches').mkdir(exist_ok=True)
rows = []
for i, task in enumerate(tasks, 1):
    t0 = time.time()
    try:
        r = run_sync(evaluator.evaluate_task, task=task, task_index=i, total_tasks=len(tasks))
        rec = dump(r)
        patch = (getattr(r, 'agent_patch', '') or '').strip()
        (OUT / 'patches' / f'{task.instance_id}.patch').write_text(patch)
        rec.update(instance_id=task.instance_id, repo=task.repo)
    except Exception as exc:
        rec = {'instance_id': task.instance_id, 'repo': task.repo, 'resolved': False,
               'agent_error': f'{type(exc).__name__}: {exc}', 'traceback': traceback.format_exc()}
    rec['wall_seconds'] = round(time.time() - t0, 1)
    rows.append(rec)
    with open(OUT / 'kernel_results.jsonl', 'a') as f:
        f.write(json.dumps(rec, default=str) + '\n')
    print(f'[{i}/{len(tasks)}] {task.instance_id} resolved={rec.get("resolved")} '
          f'calls={rec.get("tool_calls", rec.get("tool_calls_used"))} '
          f'wall={rec["wall_seconds"]}s err={str(rec.get("agent_error") or rec.get("error") or "")[:200]}',
          flush=True)

if server is not None:
    server.stop()

# 5. Smoke checks: did the analyzer emit all seven sections, and did the coder submit?
SECTIONS = ['FAILING_TEST', 'TRACEBACK', 'FILES', 'CODE', 'DIAGNOSIS', 'EDIT_SITES', 'RISK']
report = {'tag': TAG, 'model': MODEL_NAME, 'tasks': len(rows),
          'resolved': sum(1 for r in rows if r.get('resolved')), 'per_task': {}}
for r in rows:
    tid = r['instance_id']
    blob = ''
    for p in OUT.rglob('*'):
        if p.is_file() and tid in p.name and p.suffix in {'.json', '.log', '.txt', '.jsonl'}:
            blob += p.read_text(errors='replace')
    report['per_task'][tid] = {
        'resolved': r.get('resolved'),
        'sections_found': [s for s in SECTIONS if f'### {s}' in blob],
        'analyzer_called': 'code_analyzer' in blob,
        'submit_patch_called': 'submit_patch' in blob,
        'patch_chars': len((OUT / 'patches' / f'{tid}.patch').read_text())
        if (OUT / 'patches' / f'{tid}.patch').exists() else 0,
    }
(OUT / 'kernel_report.json').write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))
print('files in results:', sorted(str(p.relative_to(OUT)) for p in OUT.rglob('*') if p.is_file())[:50])
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True, help="Kaggle username that owns the kernel")
    ap.add_argument("--tag", default="smoke")
    ap.add_argument("--model", choices=MODELS, default="e4b")
    ap.add_argument("--zip", default=None, help="defaults to dist/<model>.zip")
    ap.add_argument("--task-ids", nargs="*", default=[])
    ap.add_argument("--skip-agent-patch", action="store_true")
    ap.add_argument("--accelerator", default="NvidiaL4X4")
    a = ap.parse_args()

    zpath = Path(a.zip or f"dist/{a.model}.zip")
    b64 = base64.b64encode(zpath.read_bytes()).decode()
    src = (TEMPLATE.replace("__TAG__", repr(a.tag))
           .replace("__MODEL__", repr(MODELS[a.model]))
           .replace("__TASK_IDS__", repr(a.task_ids))
           .replace("__SKIP__", repr(a.skip_agent_patch))
           .replace("__ZIP__", repr(b64)))

    slug = f"gemma-agent-{a.tag}".lower().replace("_", "-")
    out = Path("kaggle") / a.tag
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(src, encoding="utf-8")
    meta = {
        "id": f"{a.user}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": not a.skip_agent_patch,
        "enable_internet": False,
        "machine_shape": "" if a.skip_agent_patch else a.accelerator,
        "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"],
        "competition_sources": ["gemma-4-developer-agent"],
        "kernel_sources": [],
        "model_sources": [] if a.skip_agent_patch
        else [f"google/gemma-4/other/{MODELS[a.model]}/2"],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"wrote {out}/run.py ({len(src)} chars) and kernel-metadata.json  id={meta['id']}")


if __name__ == "__main__":
    main()
